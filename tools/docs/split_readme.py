#!/usr/bin/env python3
"""Split README.md into one documentation page per `##` section.

    split_readme.py            split the README into docs/*.md, then sync the navigation and the contents
    split_readme.py sync       only sync the navigation (zensical*.toml) and the contents (index.md), EN and FR

The README is the source of truth: its text is cut, never rewritten. The only changes made to it are structural:
headings move up one level (the `##` title of a section becomes the `#` title of its page), `#anchor` links point to
the page that owns the heading, relative links to repository files become absolute GitHub URLs, and the decorative
HTML header of the README (logo, badge) is replaced by the logo images of the theme.

Standard library only: nothing to install.
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
README = ROOT / "README.md"
DOCS = ROOT / "docs"
DOCS_FR = DOCS / "fr"
CACHE = DOCS / ".translation-cache.json"
CONFIGS = {"en": ROOT / "zensical.toml", "fr": ROOT / "zensical.fr.toml"}

TOC_BEGIN = "<!-- BEGIN TOC (generated by split_readme.py) -->"
TOC_END = "<!-- END TOC -->"
TOC_TITLE = {"en": "Contents", "fr": "Sommaire"}
NAV_BEGIN = "# BEGIN NAV (generated by split_readme.py, do not edit by hand)"
NAV_END = "# END NAV"
HOME_TITLE = {"en": "Home", "fr": "Accueil"}

FENCE = re.compile(r"^\s*(```|~~~)")


@dataclass
class Section:
    title: str
    slug: str
    lines: list[str] = field(default_factory=list)


def fail(message: str) -> None:
    sys.exit(f"split_readme: {message}")


def kebab(title: str) -> str:
    """`How it works` → `how-it-works` (accents dropped, anything that is not a letter or a digit is a separator)."""
    import unicodedata

    plain = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", plain.lower()).strip("-")


def github_anchor(title: str) -> str:
    """The anchor GitHub gives to a heading (what the README links use)."""
    text = re.sub(r"`|\*|_", "", title).strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)

    return text.replace(" ", "-")


def outside_fences(lines: list[str]):
    """Yield (line, in_code) for every line, `in_code` being true inside a fenced block."""
    in_code = False
    for line in lines:
        if FENCE.match(line):
            yield line, True
            in_code = not in_code
            continue
        yield line, in_code


def split(text: str) -> tuple[list[str], list[Section]]:
    intro: list[str] = []
    sections: list[Section] = []
    current: Section | None = None

    for line, in_code in outside_fences(text.splitlines()):
        match = None if in_code else re.match(r"^## (.+?)\s*$", line)
        if match:
            title = match.group(1)
            current = Section(title, kebab(title))
            sections.append(current)
            continue
        (current.lines if current else intro).append(line)

    return intro, sections


def trim(lines: list[str]) -> list[str]:
    while lines and not lines[0].strip():
        lines = lines[1:]
    while lines and not lines[-1].strip():
        lines = lines[:-1]

    return lines


def strip_html_header(intro: list[str]) -> list[str]:
    """Drop the leading raw HTML blocks of the README (centered logo, badges): the theme shows the logo itself."""
    blocks = "\n".join(intro).strip().split("\n\n")
    while blocks and blocks[0].lstrip().startswith("<"):
        blocks.pop(0)

    return "\n\n".join(blocks).splitlines()


def demote(lines: list[str]) -> list[str]:
    """Move every heading up one level (`###` → `##`), the code blocks left alone."""
    result = []
    for line, in_code in outside_fences(lines):
        match = None if in_code else re.match(r"^(#{3,6}) (.*)$", line)
        result.append(f"{match.group(1)[1:]} {match.group(2)}" if match else line)

    return result


def repo_url(text: str) -> str:
    match = re.search(r"https://github\.com/([\w.-]+/[\w.-]+?)(?:/|\.git|\b)", text)
    if not match:
        fail("cannot find the GitHub repository URL in the README")

    return f"https://github.com/{match.group(1)}"


def rewrite_links(lines: list[str], page: str, owners: dict[str, str], repo: str) -> list[str]:
    """Fix the `](target)` links: `#anchor` → owning page, repository file → GitHub, outside the code blocks."""

    def fix(match: re.Match[str]) -> str:
        target = match.group(2)
        if target.startswith("#"):
            anchor = target[1:]
            owner = owners.get(anchor)
            if owner is None:
                fail(f"the link `{target}` of the page `{page}` points to no heading of the README")
            if owner == page:
                return match.group(0)
            suffix = "" if owners["@" + owner] == anchor else f"#{anchor}"
            return f"{match.group(1)}({owner}.md{suffix})"
        if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("/"):
            return match.group(0)
        return f"{match.group(1)}({repo}/blob/main/{target})"

    result = []
    for line, in_code in outside_fences(lines):
        result.append(line if in_code else re.sub(r"(\[[^\]]*\])\(([^)\s]+)\)", fix, line))

    return result


def write_pages(intro: list[str], sections: list[Section], repo: str) -> None:
    # Which page owns which README anchor.
    owners: dict[str, str] = {}
    for section in sections:
        owners[github_anchor(section.title)] = section.slug
        owners["@" + section.slug] = github_anchor(section.title)
        for line, in_code in outside_fences(section.lines):
            match = None if in_code else re.match(r"^#{3,6} (.+?)\s*$", line)
            if match:
                owners.setdefault(github_anchor(match.group(1)), section.slug)

    DOCS.mkdir(exist_ok=True)
    for old in DOCS.glob("*.md"):
        old.unlink()

    logos = (
        "![Rustine](img/rustine-logo.svg#only-light)\n"
        "![Rustine](img/rustine-logo-dark.svg#only-dark)"
    )
    body = rewrite_links(trim(strip_html_header(intro)), "index", owners, repo)
    (DOCS / "index.md").write_text(
        f"{logos}\n\n{chr(10).join(body)}\n\n{TOC_BEGIN}\n{TOC_END}\n", encoding="utf-8"
    )

    for section in sections:
        lines = rewrite_links(demote(trim(section.lines)), section.slug, owners, repo)
        (DOCS / f"{section.slug}.md").write_text(
            f"# {section.title}\n\n{chr(10).join(lines)}\n", encoding="utf-8"
        )

    # Pages of a section that disappeared from the README.
    slugs = {section.slug for section in sections}
    if DOCS_FR.is_dir():
        for old in DOCS_FR.glob("*.md"):
            if old.stem != "index" and old.stem not in slugs:
                old.unlink()
    if CACHE.is_file():
        cache = json.loads(CACHE.read_text(encoding="utf-8"))
        kept = {slug: value for slug, value in cache.items() if slug in slugs | {"index"}}
        CACHE.write_text(json.dumps(kept, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def english_order() -> list[str]:
    """The slugs of the pages in README order, from the README itself."""
    _, sections = split(README.read_text(encoding="utf-8"))

    return [section.slug for section in sections]


def title_of(lang: str, slug: str) -> str:
    folder = DOCS_FR if lang == "fr" else DOCS
    path = folder / f"{slug}.md"
    if not path.is_file():
        path = DOCS / f"{slug}.md"  # not translated yet: fall back to the English page
    match = re.search(r"^# (.+?)\s*$", path.read_text(encoding="utf-8"), re.M)

    return match.group(1) if match else slug


def sync() -> None:
    slugs = english_order()
    for lang, config in CONFIGS.items():
        # Contents of the home page.
        index = (DOCS_FR if lang == "fr" else DOCS) / "index.md"
        if index.is_file():
            items = "\n".join(f"- [{title_of(lang, slug)}]({slug}.md)" for slug in slugs)
            block = f"{TOC_BEGIN}\n## {TOC_TITLE[lang]}\n\n{items}\n{TOC_END}"
            content = index.read_text(encoding="utf-8")
            if TOC_BEGIN not in content:
                content = content.rstrip("\n") + f"\n\n{TOC_BEGIN}\n{TOC_END}\n"
            index.write_text(
                re.sub(re.escape(TOC_BEGIN) + r".*?" + re.escape(TOC_END), lambda _: block, content, flags=re.S),
                encoding="utf-8",
            )

        # Navigation of the site.
        if not config.is_file():
            continue
        entries = [f'  {{ "{HOME_TITLE[lang]}" = "index.md" }},']
        entries += [f'  {{ "{title_of(lang, slug)}" = "{slug}.md" }},' for slug in slugs]
        block = f"{NAV_BEGIN}\nnav = [\n" + "\n".join(entries) + f"\n]\n{NAV_END}"
        content = config.read_text(encoding="utf-8")
        if NAV_BEGIN not in content:
            fail(f"{config.name} has no `{NAV_BEGIN}` / `{NAV_END}` markers")
        config.write_text(
            re.sub(re.escape(NAV_BEGIN) + r".*?" + re.escape(NAV_END), lambda _: block, content, flags=re.S),
            encoding="utf-8",
        )


def main() -> None:
    if not README.is_file():
        fail(f"{README} not found")
    if sys.argv[1:] not in ([], ["sync"]):
        fail(__doc__.strip().splitlines()[0])

    if not sys.argv[1:]:
        text = README.read_text(encoding="utf-8")
        intro, sections = split(text)
        if not sections:
            fail("no `##` section in the README")
        write_pages(intro, sections, repo_url(text))
        print(f"README split into {len(sections)} pages + index: " + ", ".join(s.slug for s in sections))

    sync()


if __name__ == "__main__":
    main()
