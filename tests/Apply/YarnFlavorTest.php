<?php

declare(strict_types=1);

namespace Rustine\Tests\Apply;

use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;
use Rustine\Apply\YarnFlavor;

final class YarnFlavorTest extends TestCase
{
    #[Test]
    public function theLockfileFormatGivesTheFlavor(): void
    {
        self::assertSame(YarnFlavor::Berry, YarnFlavor::ofLockfile("# This file is generated by running \"yarn install\".\n\n__metadata:\n  version: 8\n"));
        self::assertSame(YarnFlavor::Classic, YarnFlavor::ofLockfile("# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n\n\"a@^1\":\n  version \"1.0.0\"\n"));
    }

    #[Test]
    public function theMajorVersionGivesTheFlavor(): void
    {
        self::assertSame(YarnFlavor::Classic, YarnFlavor::ofVersion('1.22.19'));
        self::assertSame(YarnFlavor::Berry, YarnFlavor::ofVersion('4.2.2'));
        self::assertSame(YarnFlavor::Berry, YarnFlavor::ofVersion('v3.6.4'));
        self::assertNull(YarnFlavor::ofVersion('unknown'));
    }
}
